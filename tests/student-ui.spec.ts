import { test, expect } from '@playwright/test';

test('compact guide, hardware emphasis and personal notebook', async ({ page }) => {
  test.setTimeout(120000);
  await page.goto('/');
  await page.locator('.archive-index-trigger').click();
  await page.locator('#archive-index').getByRole('button', { name: /apollo/i }).click();
  await expect(page.locator('.surface-guide')).toBeVisible();
  await expect(page.locator('.expedition-log')).toHaveCount(0);
  await page.locator('.surface-guide button').click();
  await expect(page.locator('dialog[open]')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.locator('.surface-guide button')).toBeFocused();
  await page.getByRole('button', {name:'NOTEBOOK',exact:true}).click();
  await page.getByLabel('My thoughts & questions').fill('Why did they choose this landing gear?');
  await expect(page.getByRole('status')).toContainText('Saved on this device');
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button', {name:'NOTEBOOK',exact:true})).toBeFocused();
  await page.reload();
  await page.getByRole('button', {name:'NOTEBOOK',exact:true}).click();
  await expect(page.getByLabel('My thoughts & questions')).toHaveValue('Why did they choose this landing gear?');
  await page.screenshot({path:'docs/qa/curiosity-notebook-desktop.png'});
  await page.keyboard.press('Escape');
  await page.locator('.archive-index-trigger').click();
  await page.locator('#archive-index').getByRole('button', { name: /apollo/i }).click();
  await expect(page.locator('canvas')).toHaveAttribute('data-world','lunar',{timeout:60000});
  await expect(page.locator('canvas')).toHaveAttribute('aria-busy','false',{timeout:60000});
  await page.screenshot({path:'docs/qa/compact-guide-desktop.png'});
  await page.locator('.discovery-dock [data-artifact="eagle"]').click();
  await expect(page.locator('.cutaway-controls button').first()).toHaveText('Separate hardware');
  await page.getByRole('button',{name:'Separate hardware',exact:true}).click();
  await expect(page.getByRole('button',{name:'Assemble hardware',exact:true})).toHaveAttribute('aria-pressed','true');
  await page.getByText('More model controls', {exact:true}).click();
  await page.getByRole('button', {name:'Zoom out',exact:true}).click();
  await page.getByRole('button', {name:'Zoom out',exact:true}).click();
  await page.getByText('More model controls', {exact:true}).click();
  const part=page.locator('.component-switch button').first();
  await part.hover();
  await expect.poll(()=>part.evaluate(el=>getComputedStyle(el).translate)).toBe('0px -3px');
  await page.screenshot({path:'docs/qa/hardware-hover-desktop.png'});
  await page.keyboard.press('Escape');
  await expect.poll(() => page.evaluate(() => document.activeElement?.getAttribute('data-artifact'))).toBe('eagle');
});
